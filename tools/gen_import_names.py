#!/usr/bin/env python3
"""SacredFire: names for the imports the host runtime serves, generated for the prepared eboot.

Reads out/link.json (unresolved_imports: "NID#library" after link_modules.py) and shadPS4's
aerolib.inl (STUB("NID", name) lines, GPL-2.0-or-later; fetched once into out/aerolib.inl unless
--aerolib points at a copy) and writes out/import_names.txt: one "NID library symbol" line per
import, symbol "?" when nothing names the NID. bb-probe loads it with --import-names so the
runtime's symbol-keyed tables bind, and STOP messages show the symbol.
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

AEROLIB_URL = 'https://raw.githubusercontent.com/shadps4-emu/shadPS4/main/src/core/aerolib/aerolib.inl'


def aerolib_names(path, url=AEROLIB_URL):
    if not path.exists():
        print(f'Fetching {url} -> {path}', file=sys.stderr)
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    return dict(re.findall(r'STUB\("([^"]+)",\s*([^)\s]+)\s*\)', path.read_text(errors='replace')))


def generate(unresolved, names):
    lines = []
    for scoped in unresolved:
        nid, _, library = scoped.partition('#')
        lines.append(f'{nid} {library or "-"} {names.get(nid, "?")}')
    return lines


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out', type=Path, default=Path(__file__).resolve().parent.parent / 'out')
    p.add_argument('--aerolib', type=Path, default=None)
    args = p.parse_args()
    link = json.loads((args.out / 'link.json').read_text())
    names = aerolib_names(args.aerolib or args.out / 'aerolib.inl')
    lines = generate(link['unresolved_imports'], names)
    target = args.out / 'import_names.txt'
    target.write_text('# NID library symbol (generated by tools/gen_import_names.py)\n' + '\n'.join(lines) + '\n')
    unnamed = sum(1 for line in lines if line.endswith(' ?'))
    print(f'Import names: {len(lines)} imports, {len(lines) - unnamed} named, {unnamed} unnamed -> {target}')


if __name__ == '__main__':
    main()
